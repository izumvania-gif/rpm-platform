import type { ReactNode } from 'react'

// «Дополнительно» на длинных формах (фаза 26 плана 2.4, F10).
//
// Первый шаг ежедневной записи — текст и одна–две связи; теги, комментарий,
// приоритет, статус, дата проверки нужны раз в неделю, а форма показывала все
// девять полей сразу. Редкие поля сворачиваются, а не удаляются — тот же
// приём, что slug на формах продукта и сегмента (фаза 22).
//
// Два правила, без которых свёртка ломает форму:
// - внутри нет `required`: обязательное поле в закрытом <details> браузер не
//   может ни показать, ни сфокусировать при проверке;
// - блок открыт, если хоть одно поле внутри уже заполнено — значение,
//   пришедшее из ссылки или из записи при редактировании, не должно быть
//   спрятано от того, кто сейчас нажмёт «Сохранить».
export function MoreFields({ open, children }: { open: boolean; children: ReactNode }) {
  return (
    <details className="sm:col-span-2" open={open}>
      <summary className="cursor-pointer text-sm text-muted-foreground">Дополнительно</summary>
      <div className="grid grid-cols-1 gap-x-6 gap-y-4 pt-3 sm:grid-cols-2">{children}</div>
    </details>
  )
}
