// Куда приземляется «Создать» (фаза 24 плана 2.4).
//
// До этого правило было одно на всех: кнопка «Новый …» на списке несёт
// `?from=/<раздел>`, и сохранение возвращает в список. Замер сценариев
// показал, что это верно для записей, которые заводят пачкой (сегменты,
// фичи, обещания, люди), и неверно для тех, с которыми работают сразу после
// создания: разговор — чтобы разобрать транскрипт на инсайты, исследование —
// чтобы описать и привязать, конкурента — чтобы дописать позиционирование и
// новость, гипотезу — чтобы записать критерий. У них «Создать» возвращал в
// список, и человек тут же кликал по только что созданной записи.
//
// Правило живёт здесь, в одном чистом модуле: кнопки списков, хоткей `n` и
// тест `tests/unit/new-form-return.test.ts` читают одну таблицу, и новый
// раздел не может остаться без решения — тест перечисляет все разделы с
// формой создания.

export type CreateLanding = 'list' | 'record'

/**
 * Разделы с формой создания и их приземление.
 *
 * `list` — пачковые типы: после сохранения обратно в список, следующую запись
 * заводят тут же. `record` — рабочие типы: после сохранения на карточку,
 * потому что первое, что делают с записью, делают на ней.
 */
export const CREATE_LANDING: Record<string, CreateLanding> = {
  '/segments': 'list',
  '/jtbd': 'list',
  '/features': 'list',
  '/marketing': 'list',
  '/insights': 'list',
  '/people': 'list',
  '/departments': 'list',
  '/conversations': 'record',
  '/research': 'record',
  '/competitors': 'record',
  '/hypotheses': 'record',
}

/**
 * Адрес формы создания для кнопки «Новый …» и хоткея `n` на странице списка.
 *
 * Пачковый тип несёт `?from=`, чтобы `createX` вернул в список; рабочий — не
 * несёт, и `createX` приземляет на карточку своим умолчанием.
 */
export function newRecordHref(section: string): string {
  const landing = CREATE_LANDING[section]
  return landing === 'list' ? `${section}/new?from=${section}` : `${section}/new`
}
