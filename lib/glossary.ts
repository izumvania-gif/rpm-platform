// Словарь понятий — одна фраза на каждое (фаза 27 плана 2.4).
//
// Подсказки на заголовках секций, пустые состояния и карточки модулей читают
// одну и ту же фразу — тот же приём, что правило одного словаря в фазе 19:
// понятие объясняется в одном месте, и объяснение не может разойтись между
// экранами. Фраза объясняет, **что это и что с ним считается**, а не почему
// так спроектировано.
//
// Чистый модуль без React: его читают и серверные страницы, и клиентские
// компоненты. Юнит-тест `tests/unit/glossary.test.ts` требует, чтобы каждый
// `label` встречался в исходниках интерфейса — словарь не описывает того, чего
// в интерфейсе нет.

