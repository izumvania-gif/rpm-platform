// «База знаний» как раздел, а не три соседних списка (фаза 11 редизайна 2.1).
//
// Меню сгруппировало их ещё в фазе 6, но на самих страницах группы не было
// видно: три списка, каждый со своим заголовком, и ничего, что говорило бы,
// что это один раздел. Полоса вкладок это и говорит.
//
// Маршруты остались прежними — `/research`, `/conversations`, `/insights`.
// Заводить общий префикс `/knowledge` значило бы сломать сотню существующих
// ссылок ради красоты адресной строки; вкладки — это про то, как страницы
// связаны, а не про то, где они лежат.
//
// Устроено так же, как второй уровень «Доставки» (lib/pm-nav.ts): один
// источник и для полосы вкладок, и для подменю в lib/nav-chain.ts.

export interface KnowledgeTab {
  href: string
  label: string
}

/**
 * Порядок — как знание появляется: сначала исследование как активность,
 * потом разговор внутри него, потом извлечённый из разговора инсайт.
 */
export const KNOWLEDGE_TABS: KnowledgeTab[] = [
  { href: '/research', label: 'Исследования' },
  { href: '/conversations', label: 'Разговоры' },
  { href: '/insights', label: 'Инсайты' },
]

/** Активна вкладка или одна из её вложенных страниц (`/research/<id>`). */
export function isKnowledgeTabActive(tab: KnowledgeTab, pathname: string): boolean {
  return pathname === tab.href || pathname.startsWith(`${tab.href}/`)
}
