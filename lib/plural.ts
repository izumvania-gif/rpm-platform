// Русская плюрализация — одна на приложение (сквозное, редизайн 2.1).
//
// До этого их было две, и разошлись они ровно так, как предсказывала правка 6
// плана. `lib/delete-impact.ts` возвращал только форму слова и брал `Math.abs`;
// `lib/utils.ts` возвращал «число + форму» и абсолютного значения не брал — на
// отрицательном счётчике он выдал бы «-1 продуктов». Счётчики в приложении
// неотрицательны, поэтому ошибка не проявлялась, но выбирать между двумя
// реализациями по имени файла — это уже расхождение.
//
// Здесь одна реализация и две обёртки, потому что оба вида вызова настоящие:
// где-то нужна только форма («9 сегментов» собирается по частям), где-то —
// готовая строка.

/**
 * Форма слова для счётчика.
 *
 * 1, 21, 131 → forms[0]; 2–4, 22–24 → forms[1]; 0, 5–20, 25–30 → forms[2].
 * Исключение 11–14 — причина, по которой это не `n === 1 ? a : b`.
 */
export function pluralRu(count: number, forms: [string, string, string]): string {
  const abs = Math.abs(count)
  const tens = abs % 100
  if (tens >= 11 && tens <= 14) return forms[2]
  const ones = abs % 10
  if (ones === 1) return forms[0]
  if (ones >= 2 && ones <= 4) return forms[1]
  return forms[2]
}

/** Число и форма вместе: «9 сегментов», «1 гипотеза», «2 разговора». */
export function pluralizeRu(count: number, forms: [string, string, string]): string {
  return `${count} ${pluralRu(count, forms)}`
}
