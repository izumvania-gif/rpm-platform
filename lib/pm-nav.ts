// Второй уровень «Доставки» (фаза 9 редизайна 2.1).
//
// `/pm` был одной длинной страницей на пять разделов подряд: роадмап, команда,
// экшн-планы, процессы — и всё это под одним заголовком. Из этого следовала
// known-issue из `plans/2.0-ux-improvement-plan.md`: добавление записи внизу
// уводило скролл, потому что «низ» был в полутора экранах от «верха».
//
// Пять вкладок, а не четыре, как в плане. План перечислял «Роадмап · Гант ·
// Процессы · Экшн-планы» и просто не упомянул «Команду» — но секция на `/pm`
// есть и работает, а спрятать её под одну из четырёх было бы произволом: она
// не часть роадмапа и не часть процесса.
//
// «Гант» отдельной вкладкой — тоже решение плана, и оно снимает прежний
// переключатель «Список / Гант» внутри карточки роадмапа: два способа
// переключить один и тот же вид на одном экране это один лишний.
//
// Чистый модуль: список вкладок и сборка адреса проверяются юнит-тестом, в том
// числе на то, что каждая вкладка имеет собственный маршрут (иначе меню
// обещало бы страницу, которой нет — это ловит tests/unit/nav-chain.test.ts).

export interface PmTab {
  href: string
  label: string
}

export const PM_TABS: PmTab[] = [
  { href: '/pm/roadmap', label: 'Роадмап' },
  { href: '/pm/gantt', label: 'Гант' },
  { href: '/pm/processes', label: 'Процессы' },
  { href: '/pm/action-plans', label: 'Экшн-планы' },
  { href: '/pm/team', label: 'Команда' },
]

/** Куда ведёт «Доставка» в меню и куда перебрасывает голый `/pm`. */
export const PM_DEFAULT_TAB = PM_TABS[0].href

/**
 * Адрес вкладки с сохранённым продуктом.
 *
 * Продукт живёт в query, а не в cookie активного продукта: `/pm` со своим
 * переключателем появился раньше общего (фаза 5) и умеет смотреть на продукт,
 * который сейчас не активен. Терять этот параметр при переходе между вкладками
 * нельзя — иначе переключение вкладки молча меняло бы и продукт.
 */
export function pmTabHref(href: string, productId?: string | null): string {
  return productId ? `${href}?productId=${productId}` : href
}

/** Активна вкладка или одна из её вложенных страниц (`/pm/roadmap/<id>/edit`). */
export function isPmTabActive(tab: PmTab, pathname: string): boolean {
  return pathname === tab.href || pathname.startsWith(`${tab.href}/`)
}
