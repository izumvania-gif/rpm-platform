// Активный продукт — то, что раньше жило в localStorage, а теперь в cookie.
//
// Почему не localStorage: страницы со списками — Server Components, они ходят
// в Prisma **на сервере**, а из RSC localStorage не читается. Это не деталь
// реализации, а выбор архитектуры: транспорт должен видеть сервер.
//
// Почему cookie, а не `?productId=` в URL: 77 из 78 страниц уже
// `force-dynamic`, то есть рендерятся на каждый запрос — `cookies()` не
// отнимает ни одной оптимизации кэша, потому что отнимать нечего. Параметр в
// URL пришлось бы протащить через 162 `<Link>` и он противоречил бы решению
// оставить маршруты плоскими.
//
// Здесь только чистая часть — разрешение значения по правилам. Чтение самой
// cookie и запрос к базе живут в lib/product-context.server.ts, потому что
// `cookies()` и Prisma в юнит-тесте без Next и без базы не поднять.

export const ACTIVE_PRODUCT_COOKIE = 'rpm_active_product'

/** Год: это предпочтение отображения, а не сессия. */
export const ACTIVE_PRODUCT_COOKIE_MAX_AGE = 60 * 60 * 24 * 365

/**
 * Какой продукт считать активным.
 *
 * Правила по порядку:
 * 1. значение из cookie — но только если такой продукт существует и
 *    принадлежит этому пользователю;
 * 2. иначе первый продукт из списка (список приходит уже отсортированным по
 *    имени — «первый по алфавиту», а не «первый созданный»: у пустого
 *    workspace порядок создания ничего не значит, а имя предсказуемо);
 * 3. иначе null — продуктов вообще нет.
 *
 * Пункт 1 проверяет принадлежность намеренно: cookie приходит от клиента, её
 * можно поставить руками. Без проверки чужой (или уже удалённый) id молча
 * стал бы «активным продуктом» и все списки отфильтровались бы в пустоту.
 */
export function resolveActiveProductId(
  cookieValue: string | undefined,
  ownedProductIds: string[]
): string | null {
  if (cookieValue && ownedProductIds.includes(cookieValue)) return cookieValue
  return ownedProductIds[0] ?? null
}

/**
 * Виден ли пользователю этот продукт при текущем активном.
 *
 * Нужно для карточек записей: открытая по прямой ссылке запись из другого
 * продукта — это не ошибка доступа (продукт свой), а рассинхрон контекста.
 * Экран не должен показывать данные одного продукта в контексте другого.
 */
export function isActiveProduct(activeProductId: string | null, productId: string): boolean {
  return activeProductId === productId
}

/**
 * Кусок `where` для запроса, отфильтрованного по активному продукту.
 *
 * Спред, а не `productId: id!`: продуктов может не быть вовсе. Тогда
 * фильтровать не по чему — и список пуст сам по себе, потому что записи без
 * продукта в этой схеме невозможны. Возвращать `{ productId: null }` было бы
 * враньём: это условие «у записи нет продукта», а не «продукт не выбран».
 */
export function activeProductFilter(activeProductId: string | null): { productId?: string } {
  return activeProductId ? { productId: activeProductId } : {}
}
